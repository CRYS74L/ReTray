"""Generate desktop and web device icons from the same pinned Lucide SVGs."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1] / "src" / "LanDeviceMonitor.App"
mapping = {"手机":"smartphone", "平板电脑":"tablet", "笔记本电脑":"laptop-minimal", "台式电脑":"monitor",
           "路由器":"router", "智能音箱":"speaker", "灯":"lightbulb", "插座":"plug", "空调":"air-vent",
           "监测设备":"gauge", "窗帘":"blinds", "传感器":"radio", "电视":"tv-minimal", "游戏设备":"gamepad-2", "摄像头":"webcam", "其他设备":"cpu"}
geometry, markup = {}, {}
for name in mapping.values():
    override = root / "Assets" / "IconOverrides" / f"{name}.svg"
    svg = ET.parse(override if override.exists() else root / "ThirdParty" / "lucide" / "icons" / f"{name}.svg").getroot()
    parts, elements = [], []
    for el in svg:
        tag = el.tag.split("}")[-1]
        a = el.attrib
        elements.append("<" + tag + " " + " ".join(f'{k}="{v}"' for k,v in a.items()) + "/>")
        n = lambda key, default=0: float(a.get(key,default))
        if tag == "path": parts.append(a["d"])
        elif tag in ("circle", "ellipse"):
            x,y,rx,ry=n("cx"),n("cy"),n("r",n("rx")),n("r",n("ry"))
            parts.append(f"M{x-rx},{y} A{rx},{ry} 0 1 0 {x+rx},{y} A{rx},{ry} 0 1 0 {x-rx},{y} Z")
        elif tag == "rect":
            x,y,w,h,rx=n("x"),n("y"),n("width"),n("height"),n("rx")
            parts.append(f"M{x+rx},{y} H{x+w-rx} A{rx},{rx} 0 0 1 {x+w},{y+rx} V{y+h-rx} A{rx},{rx} 0 0 1 {x+w-rx},{y+h} H{x+rx} A{rx},{rx} 0 0 1 {x},{y+h-rx} V{y+rx} A{rx},{rx} 0 0 1 {x+rx},{y} Z")
        elif tag == "line": parts.append(f'M{a["x1"]},{a["y1"]} L{a["x2"]},{a["y2"]}')
        elif tag in ("polyline","polygon"): parts.append("M"+a["points"]+(" Z" if tag=="polygon" else ""))
        else: raise ValueError(tag)
    geometry[name]=parts
    markup[name]="".join(elements)
lines=["// Generated by scripts/build-device-icons.py from pinned Lucide sources.","using System.Windows.Media;", "namespace LanDeviceMonitor.Controls;", "internal static class DeviceIconCatalog", "{", "    internal static Geometry Get(string type) => Icons.GetValueOrDefault(LanDeviceMonitor.Models.DeviceIdentity.NormalizeTypeName(type), Icons[\"其他设备\"]);", "    private static Geometry Icon(params string[] paths) { var group = new GeometryGroup(); foreach(var path in paths) group.Children.Add(Geometry.Parse(path)); group.Freeze(); return group; }", "    private static readonly Dictionary<string, Geometry> Icons = new()", "    {"]
lines += [f'        [{json.dumps(t,ensure_ascii=False)}] = Icon('+", ".join(json.dumps(p) for p in geometry[n])+'),' for t,n in mapping.items()]
lines += ["    };","}"]
(root/"Controls"/"DeviceIconCatalog.cs").write_text("\n".join(lines)+"\n",encoding="utf-8")
(root/"Web"/"device-icons.js").write_text("// Generated from the same pinned Lucide SVGs as the desktop.\nexport const deviceIconNames = "+json.dumps(mapping,ensure_ascii=False)+";\nexport const deviceIconPaths = "+json.dumps(markup,ensure_ascii=False)+";\n",encoding="utf-8")
